/* Flagship "Latest" section + data-driven hero cards.
   Reads window.LATEST (assets/latest_data.js, regenerated by work/gen_latest.py on every data refresh).
   Renders all text in the active language itself (no dictionary dependency), re-renders on language switch. */
(function(){
  'use strict';
  var L = window.LATEST; if(!L) return;
  var charts = [];
  function en(){ return (window.SP_LANG ? SP_LANG()==='en' : document.body.classList.contains('en')); }
  function $(id){ return document.getElementById(id); }
  function set(id, html){ var e=$(id); if(e) e.innerHTML = html; }
  function esc(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;'); }
  function nm(o){ return en() ? o.en : o.zh; }
  /* volumes: data in 万吨; EN shows Mt */
  function vol(v, d){ if(v==null) return '—'; if(en()){ var x=v/100; return x.toLocaleString('en-US',{minimumFractionDigits:d==null?2:d,maximumFractionDigits:d==null?2:d}); } return v.toLocaleString('en-US',{minimumFractionDigits:d==null?1:d,maximumFractionDigits:d==null?1:d}); }
  function unit(){ return en() ? 'Mt' : '万吨'; }
  function cv(v){ return v==null ? null : (en() ? Math.round(v)/100 : Math.round(v*10)/10); }
  function pct(v, d){ if(v==null) return '—'; d=(d==null?1:d); return (v>=0?'+':'−')+Math.abs(v).toFixed(d)+'%'; }
  function sgn(v){ return v>=0 ? 'up' : 'dn'; }
  var M = L.meta, K = L.kpi, CY = M.cy, PY = M.py;
  var lastM = M.months[M.months.length-1];
  var MON_EN = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

  var TIP = {backgroundColor:'rgba(13,18,32,.96)', borderColor:'#22304d', textStyle:{color:'#e8edf6',fontSize:12}};
  var AX = {axisLine:{lineStyle:{color:'#2a3a58'}}, axisTick:{show:false}, axisLabel:{color:'#a9b4c8',fontSize:11.5}};
  var GOLD = ['#b97a13','#f0b860'], RED = ['#8a0000','#e23b3b'];
  function grad(c){ return new echarts.graphic.LinearGradient(0,0,1,0,[{offset:0,color:c[0]},{offset:1,color:c[1]}]); }

  function divBar(el, rows, valFn, labFn, tipFn){
    var ch = echarts.init(el); charts.push(ch);
    var names = rows.map(function(r){ return labFn(r); });
    var vals = rows.map(valFn);
    ch.setOption({
      animationDuration:700,
      grid:{left:6,right:56,top:8,bottom:8,containLabel:true},
      tooltip:Object.assign({trigger:'axis',axisPointer:{type:'shadow'},formatter:function(p){ return tipFn(rows[p[0].dataIndex]); }},TIP),
      xAxis:{type:'value',axisLabel:{show:false},splitLine:{lineStyle:{color:'rgba(255,255,255,.05)'}},axisLine:{show:false}},
      yAxis:Object.assign({type:'category',inverse:true,data:names},AX,{axisLabel:{color:'#cfd7e6',fontSize:12,fontWeight:600}}),
      series:[{type:'bar',data:vals,barWidth:'58%',
        label:{show:true,position:'right',color:'#9aa6bb',fontSize:11,formatter:function(p){ var v=p.value; return (v>=0?'+':'−')+Math.abs(v).toLocaleString('en-US',{maximumFractionDigits:en()?2:0,minimumFractionDigits:en()?2:0}); }},
        itemStyle:{borderRadius:3,color:function(p){ return grad(p.value>=0?GOLD:RED); }}}]
    });
  }

  function renderCards(){
    var C = L.cards || {}, lg = en() ? 'en' : 'zh';
    if(C.c01){ set('ic1t', esc(C.c01.ti[lg])); set('ic1d', C.c01.ds[lg]); }
    if(C.c03){ set('ic3d', C.c03.ds[lg]); }
    if(C.c04){ set('ic4t', esc(C.c04.ti[lg])); set('ic4d', C.c04.ds[lg]); }
  }

  function render(){
    if(!$('latest')) return;
    var E = en();
    charts.forEach(function(c){ try{ c.dispose(); }catch(e){} }); charts = [];
    var mLast = parseInt(lastM.slice(5),10);
    set('ltEyebrow', E ? 'Latest '+CY+' · Year to date' : CY+' 最新动态 · Latest');
    set('ltTitle', esc(E ? L.title.en : L.title.zh) + '<span class="lt-badge"><i></i>'+(E ? 'Updated to '+MON_EN[mLast-1]+' '+CY : '数据更新至 '+lastM)+'</span>');
    set('ltSub', E
      ? 'Based on Global Trade Tracker (GTT) monthly customs data for the '+M.reps+' largest steel-trading reporters. H1 '+CY+' compared with H1 '+PY+'; volumes in Mt, reporter-declared.'
      : '基于 Global Trade Tracker（GTT）'+M.reps+' 个主要钢材贸易报告国的月度海关数据，'+CY+' 年上半年对比 '+PY+' 年上半年；单位万吨，报告国申报口径。');

    /* KPI strip */
    var kp = [
      {v:vol(K.exp.c,E?1:0), u:unit(), ch:K.exp.yoy, k:E?('Exports · '+M.reps+' reporters · H1 '+CY):(M.reps+' 国出口 · '+CY+' 上半年')},
      {v:vol(K.imp.c,E?1:0), u:unit(), ch:K.imp.yoy, k:E?('Imports · '+M.reps+' reporters · H1 '+CY):(M.reps+' 国进口 · '+CY+' 上半年')},
      {v:vol(K.cn.c,E?1:0), u:unit(), ch:K.cn.yoy, k:E?('China exports · H1 '+CY):('中国出口 · '+CY+' 上半年')},
      {v:esc(nm(K.prodUp)), sm:true, ch:K.prodUp.yoy, k:E?'Fastest-growing product':'增量最大品种'},
      {v:esc(nm(K.impDn)), sm:true, ch:K.impDn.yoy, k:E?'Largest import decline':'进口降幅最大'}
    ];
    set('ltKpi', kp.map(function(x){
      return '<div class="bn"><div class="v num'+(x.sm?' sm':'')+'">'+x.v+(x.u?'<span class="u">'+x.u+'</span>':'')+
        '<span class="'+sgn(x.ch)+'">'+pct(x.ch)+'</span></div><div class="k">'+x.k+'</div></div>';
    }).join(''));

    var EC = !!window.echarts;
    /* 1. monthly trend */
    var S = L.monthly.series, mons = L.monthly.months;
    var top = S[0], avg = 0, n = 0; top.v.forEach(function(v){ if(v!=null){ avg+=v; n++; } }); avg = n?avg/n:0;
    set('lt1t', E ? (top.en+' averages '+vol(avg,1)+' Mt a month, far ahead of the pack') : (top.zh+'月均出口 '+vol(avg,0)+' 万吨，遥遥领先'));
    set('lt1g', E ? 'Monthly · '+CY : CY+' · 月度');
    set('lt1s', E ? 'Exports of the six largest exporters; unit: Mt · latest months cover only reporters that have published' : '六大出口国月度出口量；单位：万吨 · 末月仅含已发布数据的国家');
    function lgName(s,i){ return nm(s)+((i===undefined?S.indexOf(s):i)===0?(E?' (LHS)':'（左轴）'):''); }
    var pal = ['#e23b3b','#e8a13a','#f3d17a','#5a8cf2','#38c1a6','#b6bfd0'];
    if(EC){ var ch1 = echarts.init($('ltMonthly')); charts.push(ch1);
    ch1.setOption({
      animationDuration:700, color:pal,
      grid:{left:6,right:10,top:52,bottom:6,containLabel:true},
      legend:{top:0,left:0,itemWidth:14,itemHeight:3,textStyle:{color:'#a9b4c8',fontSize:11.5},data:S.map(lgName)},
      tooltip:Object.assign({trigger:'axis',axisPointer:{type:'shadow'},valueFormatter:function(v){ return v==null?'—':v.toLocaleString('en-US',{maximumFractionDigits:E?2:1})+' '+unit(); }},TIP),
      xAxis:Object.assign({type:'category',boundaryGap:true,data:mons.map(function(m){ return E?MON_EN[m-1]:m+'月'; })},AX),
      yAxis:[{type:'value',name:E?'China (LHS)':'中国（左轴）',nameTextStyle:{color:'#e88',fontSize:10.5,align:'left'},min:0,axisLabel:{color:'#e88',fontSize:11},splitLine:{lineStyle:{color:'rgba(255,255,255,.06)'}}},
             {type:'value',name:E?'Others (RHS)':'其他（右轴）',nameTextStyle:{color:'#a9b4c8',fontSize:10.5,align:'right'},axisLabel:{color:'#7e8aaa',fontSize:11},splitLine:{show:false}}],
      series:S.map(function(s,i){
        if(i===0) return {name:lgName(s,i),yAxisIndex:0,type:'bar',barWidth:'46%',z:1,data:s.v.map(cv),
          itemStyle:{borderRadius:[3,3,0,0],color:new echarts.graphic.LinearGradient(0,0,0,1,[{offset:0,color:'rgba(226,59,59,.6)'},{offset:1,color:'rgba(138,0,0,.25)'}])}};
        return {name:lgName(s,i),yAxisIndex:1,type:'line',smooth:0.2,symbol:'circle',symbolSize:5,connectNulls:false,z:3,lineStyle:{width:2,color:pal[i]},itemStyle:{color:pal[i]},data:s.v.map(cv)}; })
    }); }

    /* 2. exporter movers */
    var ex = L.expUp.concat(L.expDn.slice().reverse());
    set('lt2t', E ? (L.expUp[0].en+' adds the most, '+L.expDn[0].en+' falls the most') : (L.expUp[0].zh+'增量最大，'+L.expDn[0].zh+'降幅最深'));
    set('lt2g', E ? 'H1 '+CY+' vs H1 '+PY : CY+'H1 vs '+PY+'H1');
    set('lt2s', E ? 'Change in exports, H1 y/y; unit: Mt' : '上半年出口同比变化量；单位：万吨');
    var tipRow = function(r){ return '<b>'+esc(nm(r))+'</b><br/>H1 '+CY+': '+vol(r.c)+' '+unit()+'<br/>H1 '+PY+': '+vol(r.p)+' '+unit()+'<br/>'+(E?'Change':'变化')+': <b>'+(r.d>=0?'+':'−')+vol(Math.abs(r.d))+'</b> ('+pct(r.yoy)+')'; };
    if(EC) divBar($('ltExpDelta'), ex, function(r){ return cv(r.d); }, nm, tipRow);

    /* 3. product y/y */
    var pr = L.prod.slice().sort(function(a,b){ return b.yoy-a.yoy; });
    set('lt3t', E ? (K.prodUp.en+' surges, '+K.prodDn.en+' retreats') : (K.prodUp.zh+'放量，'+K.prodDn.zh+'回落'));
    set('lt3g', E ? 'By product' : '分品种');
    set('lt3s', E ? 'Exports by product, H1 y/y; unit: %' : '上半年分品种出口同比；单位：%');
    if(EC){ var ch3 = echarts.init($('ltProd')); charts.push(ch3);
    ch3.setOption({
      animationDuration:700,
      grid:{left:6,right:52,top:6,bottom:6,containLabel:true},
      tooltip:Object.assign({trigger:'axis',axisPointer:{type:'shadow'},formatter:function(p){ var r=pr[p[0].dataIndex]; return '<b>'+esc(nm(r))+'</b><br/>H1 '+CY+': '+vol(r.c)+' '+unit()+'<br/>'+(E?'y/y':'同比')+': <b>'+pct(r.yoy)+'</b>'; }},TIP),
      xAxis:{type:'value',axisLabel:{show:false},splitLine:{lineStyle:{color:'rgba(255,255,255,.05)'}}},
      yAxis:Object.assign({type:'category',inverse:true,data:pr.map(nm)},AX,{axisLabel:{color:'#cfd7e6',fontSize:11.5}}),
      series:[{type:'bar',data:pr.map(function(r){ return r.yoy==null?0:Math.round(r.yoy*10)/10; }),barWidth:'60%',
        label:{show:true,position:'right',color:'#9aa6bb',fontSize:11,formatter:function(p){ return pct(p.value); }},
        itemStyle:{borderRadius:3,color:function(p){ return grad(p.value>=0?GOLD:RED); }}}]
    }); }

    /* 4. importer movers */
    var im = L.impUp.concat(L.impDn.slice().reverse());
    set('lt4t', E ? (L.impDn[0].en+' cuts imports the most, '+L.impUp[0].en+' adds the most') : (L.impDn[0].zh+'进口降幅最大，'+L.impUp[0].zh+'增量居首'));
    set('lt4g', E ? 'H1 '+CY+' vs H1 '+PY : CY+'H1 vs '+PY+'H1');
    set('lt4s', E ? 'Change in imports, H1 y/y; unit: Mt' : '上半年进口同比变化量；单位：万吨');
    if(EC) divBar($('ltImpDelta'), im, function(r){ return cv(r.d); }, nm, tipRow);

    /* corridors */
    function corRows(arr){
      var mx = 0; arr.forEach(function(r){ mx=Math.max(mx,r.c,r.p); });
      return arr.map(function(r,i){
        return '<div class="bil-row"><div class="bi num">'+(i+1)+'</div>'+
          '<div class="bil-route">'+esc(E?r.fen:r.f)+' <span class="ar">&rarr;</span> '+esc(E?r.ten:r.t)+'</div>'+
          '<div class="bil-bar"><i style="width:'+(r.c/mx*100)+'%"></i></div>'+
          '<div class="bv num">'+vol(r.c)+'</div>'+
          '<div class="bil-yoy '+sgn(r.yoy)+'">'+pct(r.yoy,0)+'</div></div>';
      }).join('');
    }
    set('ltCuH', (E?'Fastest-growing corridors':'增量最大的贸易走廊')+'<span class="tag">'+(E?'GAINERS':'扩张')+'</span>');
    set('ltCdH', (E?'Fastest-shrinking corridors':'减量最大的贸易走廊')+'<span class="tag dn">'+(E?'DECLINERS':'收缩')+'</span>');
    var cs = E ? ('H1 '+CY+' exports, Mt · y/y · corridors ≥ 0.5 Mt') : (CY+' 上半年出口量（万吨）· 同比 · 规模 ≥ 50 万吨');
    set('ltCuS', cs); set('ltCdS', cs);
    set('ltCorUp', corRows(L.corUp)); set('ltCorDn', corRows(L.corDn));

    /* commentary */
    set('ltNoteH', E ? 'SMM read-out' : 'SMM 解读');
    set('ltNote', (E?L.bullets.en:L.bullets.zh).map(function(b){
      var k = b.indexOf(E?':':'：'); return '<li>'+(k>0?'<b>'+esc(b.slice(0,k+1))+'</b>'+esc(b.slice(k+1)):esc(b))+'</li>';
    }).join(''));

    /* coverage */
    set('ltCovH', E ? 'Data coverage · latest month by reporter' : '数据覆盖 · 各报告国最新月份');
    var cov = M.coverage, h = '';
    Object.keys(cov).sort().reverse().forEach(function(m){
      var mm = parseInt(m.slice(5),10);
      h += '<div class="cm">'+(E?MON_EN[mm-1]+' '+m.slice(0,4):m)+'<span>'+cov[m].length+'</span></div><div class="cl">'+cov[m].map(function(c){ return esc(nm(c)); }).join(E?' · ':'、')+'</div>';
    });
    var fh='';
    (M.flash||[]).forEach(function(f){
      var mm = parseInt(f.m.slice(5),10);
      fh += '<div class="cm" style="color:#C00000">'+(E?'Flash · '+MON_EN[mm-1]+' '+f.m.slice(0,4):f.m+' 快报')+'<span>'+f.n+'/'+f.N+'</span></div><div class="cl">'+
        f.reps.map(function(c){ return esc(nm(c))+' '+(E?(c.x/100).toFixed(2)+' Mt':c.x.toLocaleString('en-US',{minimumFractionDigits:1,maximumFractionDigits:1})+' 万吨')+(c.mom==null?'':' ('+(E?'m/m ':'环比 ')+(c.mom>=0?'+':'−')+Math.abs(c.mom).toFixed(1)+'%)'); }).join(E?' · ':'、')+
        '<br><span style="color:#8a919c">'+(E?'Exports incl. billet. Published by fewer than half of the reporters, so not yet in the aggregate analysis.':'出口量（含钢坯）。发布国家不足半数，暂不纳入汇总分析。')+'</span></div>';
    });
    h = fh + h;
    set('ltCov', h);
    set('ltSrc', E
      ? 'Source: Global Trade Tracker (GTT), national customs authorities; compiled by SMM. Basis: reporter-declared volumes (mirror data excluded), SMM 17-product steel taxonomy (HS 6-digit). H1 '+PY+' = Q1+Q2 of the quarterly series. Release lags differ by country; '+CY+' monthly totals for the latest months are therefore partial.'
      : '数据来源：Global Trade Tracker（GTT）、各国海关，SMM 整理。口径：报告国申报量（不含镜像数据），SMM 十七大钢材品种（HS 六位编码归类）；'+PY+' 年上半年为季度数据 Q1+Q2 加总。各国发布节奏不同，'+CY+' 年最近月份合计仅含已发布国家。');
  }

  function all(){ renderCards(); render(); }
  window.addEventListener('resize', function(){ charts.forEach(function(c){ try{ c.resize(); }catch(e){} }); });
  function hook(){
    var prev = window.__relangCharts;
    window.__relangCharts = function(){ if(prev) try{ prev(); }catch(e){} all(); };
    all();
  }
  if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', hook); else hook();
})();
